#!/usr/bin/env python3
"""Sinh inventory chuẩn của suite P1 từ source test.

P1 có **suite riêng** (`crm_cskh.tests.test_p1_*`) tách khỏi core inventory 99
method của P0 (P1 plan: *"Giữ P0 core inventory 99; test P1 là suite riêng"*).

Script này đọc source, liệt kê class/method, và ghi ra JSON theo cùng schema với
`g007_test_inventory.json` để `ci_junit_gate.py` dùng lại được.

Vì sao cần script thay vì JSON viết tay: một method bị **xoá** hoặc **đổi tên**
trong source sẽ biến mất khỏi inventory ⇒ gate fail (fail-closed) thay vì im lặng
chấp nhận inventory cũ.

Dùng:
    python3 deploy/dev/seed/p1_test_inventory.py --out deploy/dev/seed/p1_test_inventory.json
    python3 deploy/dev/seed/p1_test_inventory.py --check deploy/dev/seed/p1_test_inventory.json
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path


def repo_root() -> Path:
    # deploy/dev/seed/p1_test_inventory.py -> repo root
    return Path(__file__).resolve().parents[3]


def collect_module(path: Path) -> dict[str, list[str]]:
    """Trả về {class_name: [method, ...]} cho một file test."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    found: dict[str, list[str]] = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        methods = [
            child.name
            for child in node.body
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef))
            and child.name.startswith("test")
        ]
        if methods:
            found[node.name] = methods
    return found


def build_inventory(tests_dir: Path) -> dict:
    modules: dict[str, list[str]] = {}
    for path in sorted(tests_dir.glob("test_p1_*.py")):
        module = f"crm_cskh.tests.{path.stem}"
        entries: list[str] = []
        for class_name, methods in collect_module(path).items():
            for method in methods:
                entries.append(f"{class_name}.{method}")
        if entries:
            modules[module] = entries
    return {
        "schema_version": 1,
        "description": (
            "Canonical inventory of the P1 test methods. Used by ci_junit_gate.py to verify "
            "per-method runtime coverage of the separate P1 suite. Generated by "
            "deploy/dev/seed/p1_test_inventory.py; the P0 core inventory (99 methods) stays "
            "in g007_test_inventory.json."
        ),
        "expected_total": sum(len(v) for v in modules.values()),
        "modules": modules,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="P1 test inventory generator")
    parser.add_argument("--tests-dir", default=None, help="Thư mục chứa test_p1_*.py")
    parser.add_argument("--out", default=None, help="Ghi inventory JSON ra file này")
    parser.add_argument(
        "--check", default=None, help="So inventory trên disk với source"
    )
    args = parser.parse_args(argv)

    root = repo_root()
    tests_dir = (
        Path(args.tests_dir)
        if args.tests_dir
        else root / "apps/crm_cskh/crm_cskh/tests"
    )
    inventory = build_inventory(tests_dir)

    if args.check:
        expected = json.loads(Path(args.check).read_text(encoding="utf-8"))
        if expected.get("modules") != inventory["modules"]:
            print("P1 inventory does NOT match the source:", file=sys.stderr)
            print(
                json.dumps(inventory["modules"], indent=2, ensure_ascii=False),
                file=sys.stderr,
            )
            return 1
        print(
            f"P1 inventory matches the source: {inventory['expected_total']} method "
            f"trong {len(inventory['modules'])} module."
        )
        return 0

    if args.out:
        out_path = Path(args.out)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(
            json.dumps(inventory, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        print(f"wrote {out_path} ({inventory['expected_total']} method)")
        return 0

    print(json.dumps(inventory, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    try:
        # Console CI có thể dùng encoding cp1252 ⇒ ép UTF-8 để in được tiếng Việt.
        if hasattr(sys.stdout, "reconfigure"):
            sys.stdout.reconfigure(encoding="utf-8", errors="replace")
            sys.stderr.reconfigure(encoding="utf-8", errors="replace")
        sys.exit(main())
    except SystemExit:
        raise
