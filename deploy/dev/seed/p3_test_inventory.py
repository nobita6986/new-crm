#!/usr/bin/env python3
"""Generate or verify the canonical inventory of the separate P3 backend test suite.

P3 tests live in `crm_cskh.tests.test_p3_*` so that:
  * the P0 core inventory (`99` methods in `g007_test_inventory.json`) stays untouched,
  * the P1 backend inventory (`209` methods in `p1_test_inventory.json`) stays untouched, and
  * the P2 backend inventory (`38` methods in `p2_test_inventory.json`) stays untouched.

Usage:
    python3 deploy/dev/seed/p3_test_inventory.py --out deploy/dev/seed/p3_test_inventory.json
    python3 deploy/dev/seed/p3_test_inventory.py --check deploy/dev/seed/p3_test_inventory.json
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path


def repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def collect_module(path: Path) -> dict[str, list[str]]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    found: dict[str, list[str]] = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        methods = [
            child.name
            for child in node.body
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef))
            and child.name.startswith("test")
        ]
        if methods:
            found[node.name] = methods
    return found


def build_inventory(tests_dir: Path) -> dict:
    modules: dict[str, list[str]] = {}
    for path in sorted(tests_dir.glob("test_p3_*.py")):
        module = f"crm_cskh.tests.{path.stem}"
        entries: list[str] = []
        for class_name, methods in collect_module(path).items():
            for method in methods:
                entries.append(f"{class_name}.{method}")
        if entries:
            modules[module] = entries
    return {
        "schema_version": 1,
        "description": (
            "Canonical inventory of the P3 backend test methods. Used by ci_junit_gate.py to verify "
            "per-method runtime coverage of the separate P3 suite. Generated by "
            "deploy/dev/seed/p3_test_inventory.py; P0 (99), P1 (209), and P2 (38) inventories remain untouched."
        ),
        "expected_total": sum(len(v) for v in modules.values()),
        "modules": modules,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="P3 backend test inventory generator")
    parser.add_argument(
        "--tests-dir", default=None, help="Directory containing test_p3_*.py"
    )
    parser.add_argument("--out", default=None, help="Write inventory JSON to this file")
    parser.add_argument(
        "--check", default=None, help="Verify inventory on disk matches source"
    )
    args = parser.parse_args(argv)

    root = repo_root()
    tests_dir = (
        Path(args.tests_dir)
        if args.tests_dir
        else root / "apps/crm_cskh/crm_cskh/tests"
    )
    inventory = build_inventory(tests_dir)

    if args.check:
        expected = json.loads(Path(args.check).read_text(encoding="utf-8"))
        if expected.get("modules") != inventory["modules"]:
            print("P3 inventory does NOT match the source:", file=sys.stderr)
            print(
                json.dumps(inventory["modules"], indent=2, ensure_ascii=False),
                file=sys.stderr,
            )
            return 1
        print(
            f"P3 inventory matches the source: {inventory['expected_total']} methods "
            f"in {len(inventory['modules'])} modules."
        )
        return 0

    if args.out:
        out_path = Path(args.out)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(
            json.dumps(inventory, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
            newline="\n",
        )
        print(f"wrote {out_path} ({inventory['expected_total']} methods)")
        return 0

    print(json.dumps(inventory, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    try:
        if hasattr(sys.stdout, "reconfigure"):
            sys.stdout.reconfigure(encoding="utf-8", errors="replace")
            sys.stderr.reconfigure(encoding="utf-8", errors="replace")
        sys.exit(main())
    except SystemExit:
        raise
