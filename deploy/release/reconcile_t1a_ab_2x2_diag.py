def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--v2-diag-json",
        nargs="+",
        required=True,
        help="One or more T1A v2 2x2 diagnostic JSON files (in chronological order)",
    )
    ap.add_argument("--official-g18-0127b18-eval-json", default="")
    ap.add_argument("--official-g18-35f512c-eval-json", default="")
    ap.add_argument("--out-json", required=True, help="Output reconciliation JSON path")
    args = ap.parse_args(argv)

    labeled: list[tuple[str, dict[str, Any]]] = []
    for p_str in args.v2_diag_json:
        p = Path(p_str)
        labeled.append((p.stem, json.loads(p.read_text(encoding="utf-8"))))

    ev_0127 = (
        json.loads(
            Path(args.official_g18_0127b18_eval_json).read_text(encoding="utf-8")
        )
        if args.official_g18_0127b18_eval_json
        else None
    )
    ev_35f5 = (
        json.loads(
            Path(args.official_g18_35f512c_eval_json).read_text(encoding="utf-8")
        )
        if args.official_g18_35f512c_eval_json
        else None
    )

    if len(labeled) == 1 and not ev_0127 and not ev_35f5:
        rec = reconcile_v2_2x2_report(labeled[0][1])
    else:
        rec = reconcile_multi_v2_reports(
            labeled,
            official_g18_eval_0127b18=ev_0127,
            official_g18_eval_35f512c=ev_35f5,
        )
    out_p = Path(args.out_json)
    out_p.parent.mkdir(parents=True, exist_ok=True)
    out_p.write_text(
        json.dumps(rec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(
        json.dumps(
            {
                "intake_status": rec["intake_status"],
                "valid_cells": rec.get("valid_cells"),
                "rejected_cells": list((rec.get("rejected_cells") or {}).keys()),
                "decision": rec.get("decision"),
            },
            indent=2,
        )
    )
    has_all_four = set(rec.get("valid_cells") or ()) == {
        "A_idle",
        "A_busy",
        "B_idle",
        "B_busy",
    }
    return 0 if rec["intake_status"] == "RECONCILED" and has_all_four else 2


if __name__ == "__main__":
    raise SystemExit(main())
