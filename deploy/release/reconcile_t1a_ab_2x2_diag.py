#!/usr/bin/env python3
"""Fail-closed intake & SLO/resource reconciler for T1A A/B (`2x2`) G18 diagnostics.

Supports:
1. Single or multi-file `v2` 2x2 diagnostic reports (`schema_version == 'cskh-p4-t1b-ab-2x2-vps-diag-v2'`)
   generated by `run_t1a_07c93a9f_ab_2x2_diag_v2.py` (`85e838fb...`), including split runs such as
   Ops `4dc3c91` (`04a` Config A + B Trial 1 [30s client timeout on Wave 5] + `04b` Config B 120s).
2. Filtering out invalid cells (`busy_workers == 0`, uncapped `cpus_limit == 0.0`, or HTTP non-200 /
   client socket timeout errors) and reconciling only verified valid cells alongside official
   background task (`BG-01`, `BG-02`, `BG-03`) measurements from `0127b18` / `35f512c`.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

RELEASE_DIR = Path(__file__).resolve().parent
if str(RELEASE_DIR) not in sys.path:
    sys.path.insert(0, str(RELEASE_DIR))

from g18_resource_profiles import get_g18_resource_profile_spec  # noqa: E402

SIX_SLIPPED_SLO_THRESHOLDS_CAPPED: dict[str, dict[str, Any]] = {
    "SSR-01C": {"metric_key": "SSR-01C_p99_ms", "stat": "p99_ms", "max_ms": 4200.0},
    "API-00": {"metric_key": "API-00_p95_ms", "stat": "p95_ms", "max_ms": 200.0},
    "API-01C": {"metric_key": "API-01C_p95_ms", "stat": "p95_ms", "max_ms": 800.0},
    "API-02B": {"metric_key": "API-02B_p95_ms", "stat": "p95_ms", "max_ms": 1950.0},
    "AGG-03B": {"metric_key": "AGG-03B_p95_ms", "stat": "p95_ms", "max_ms": 1850.0},
    "AGG-03C": {"metric_key": "AGG-03C_p95_ms", "stat": "p95_ms", "max_ms": 3000.0},
}

EXPECTED_WAVE_COUNT_PER_CELL = 6


def _iter_cell_waves(waves_raw: Any) -> list[tuple[str, dict[str, Any]]]:
    """Normalize `cell['waves']` whether stored as a dict (unit fixtures) or list (raw v2 JSON)."""
    if isinstance(waves_raw, dict):
        return [(str(k), v) for k, v in waves_raw.items() if isinstance(v, dict)]
    if isinstance(waves_raw, list):
        out: list[tuple[str, dict[str, Any]]] = []
        for idx, item in enumerate(waves_raw):
            if isinstance(item, dict):
                wid = str(
                    item.get("wave_id") or item.get("slo_target") or f"wave_{idx}"
                )
                out.append((wid, item))
        return out
    return []


def validate_v2_cell(
    cell_id: str,
    cell: dict[str, Any],
    *,
    require_six_waves: bool = False,
) -> tuple[bool, list[str]]:
    """Verify a single v2 2x2 cell (`A_idle`, `A_busy`, `B_idle`, `B_busy`) fail-closed."""
    reasons: list[str] = []
    if not isinstance(cell, dict):
        return False, ["cell_not_object"]

    exp_cfg = "A" if cell_id.startswith("A_") else "B"
    exp_cpu = 1.5 if exp_cfg == "A" else 2.0
    exp_mem = 1536.0 if exp_cfg == "A" else 2048.0
    exp_workers = 2 if exp_cfg == "A" else 4
    exp_qs_mode = "BUSY_VERIFIED" if cell_id.endswith("_busy") else "IDLE_VERIFIED"

    topo = cell.get("topology_verified") or {}
    containers_insp = topo.get("containers_inspected") or {}
    be_insp = containers_insp.get("backend") or {}
    in_be = topo.get("in_container_gunicorn_and_cgroup") or {}

    act_cpu = float(be_insp.get("cpus_limit") or 0.0)
    if act_cpu <= 0.0:
        reasons.append(f"backend_uncapped_cpus_limit_zero:{act_cpu}")
    elif abs(act_cpu - exp_cpu) > 0.02:
        reasons.append(f"backend_cpus_limit_mismatch:expected={exp_cpu}:got={act_cpu}")

    if "memory_limit_mib" in be_insp:
        act_mem = float(be_insp.get("memory_limit_mib") or 0.0)
        if abs(act_mem - exp_mem) > 2.0:
            reasons.append(
                f"backend_memory_limit_mismatch:expected={exp_mem}:got={act_mem}"
            )

    live_w = int(in_be.get("live_gunicorn_worker_count") or 0)
    if live_w != exp_workers:
        reasons.append(
            f"live_gunicorn_worker_mismatch:expected={exp_workers}:got={live_w}"
        )

    wave_items = _iter_cell_waves(cell.get("waves"))
    if not wave_items:
        reasons.append("missing_waves_in_cell")
    else:
        if require_six_waves and len(wave_items) < EXPECTED_WAVE_COUNT_PER_CELL:
            reasons.append(
                f"incomplete_waves_in_cell:expected={EXPECTED_WAVE_COUNT_PER_CELL}:got={len(wave_items)}"
            )
        for wname, wdoc in wave_items:
            summ = (
                (wdoc or {}).get("summary") or (wdoc or {}).get("overall_summary") or {}
            )
            if isinstance(summ, dict) and int(summ.get("error_count") or 0) > 0:
                reasons.append(f"wave_{wname}_http_errors:{summ.get('error_count')}")
            qver = (wdoc or {}).get("queue_short_window_verification") or {}
            cls = str(qver.get("queue_short_classification") or "")
            if cls != exp_qs_mode:
                reasons.append(
                    f"wave_{wname}_qs_classification_mismatch:expected={exp_qs_mode}:got={cls!r}"
                )
            if exp_qs_mode == "BUSY_VERIFIED":
                if not qver.get("active_job_ids_at_start"):
                    reasons.append(f"wave_{wname}_missing_active_pds_job_at_start")
                if float(qver.get("qs_cpu_ms_during_wave") or 0.0) < 50.0:
                    reasons.append(f"wave_{wname}_insufficient_qs_cpu_ms")

    if not isinstance(cell.get("slo_metrics_summary"), dict) or not cell.get(
        "slo_metrics_summary"
    ):
        if isinstance(cell.get("waves"), list):
            reasons.append("missing_slo_metrics_summary_cell_aborted_mid_run")

    return len(reasons) == 0, reasons


def _extract_bg_slo_verdicts(eval_doc: dict[str, Any] | None) -> dict[str, Any]:
    if not isinstance(eval_doc, dict):
        return {}
    out: dict[str, Any] = {}
    for r in eval_doc.get("s1_rule_results") or []:
        if isinstance(r, dict) and str(r.get("slo_id") or "").startswith("BG-"):
            out[str(r["slo_id"])] = {
                "passed": bool(r.get("passed")),
                "failures": r.get("failures") or [],
                "scenario_key": r.get("scenario_key"),
            }
    return out


def reconcile_v2_2x2_report(
    v2_doc: dict[str, Any],
    *,
    host_mem_total_mib: float = 11960.71,
    host_mem_available_mib: float = 10148.48,
    host_mem_available_min_during_b_mib: float = 6729.35,
    host_cpu_cores: int = 6,
) -> dict[str, Any]:
    """Audit all cells in a single `v2` 2x2 report fail-closed."""
    if v2_doc.get("schema_version") != "cskh-p4-t1b-ab-2x2-vps-diag-v2":
        raise ValueError(f"Unexpected schema_version: {v2_doc.get('schema_version')!r}")
    if not bool(v2_doc.get("valid")) or v2_doc.get("diagnostic_status") != "VALID":
        return {
            "intake_status": "REJECTED_INVALID_DIAGNOSTIC_REPORT",
            "diagnostic_status": v2_doc.get("diagnostic_status"),
            "errors": v2_doc.get("errors") or [],
        }
    return reconcile_multi_v2_reports(
        [("single_v2_report", v2_doc)],
        host_mem_total_mib=host_mem_total_mib,
        host_mem_available_mib=host_mem_available_mib,
        host_mem_available_min_during_b_mib=host_mem_available_min_during_b_mib,
        host_cpu_cores=host_cpu_cores,
    )


def reconcile_multi_v2_reports(
    labeled_docs: list[tuple[str, dict[str, Any]]],
    *,
    official_g18_eval_0127b18: dict[str, Any] | None = None,
    official_g18_eval_35f512c: dict[str, Any] | None = None,
    host_mem_total_mib: float = 11960.71,
    host_mem_available_mib: float = 10148.48,
    host_mem_available_min_during_b_mib: float = 6729.35,
    host_cpu_cores: int = 6,
) -> dict[str, Any]:
    """Reconcile one or more `v2` diagnostic files (e.g. Ops `4dc3c91` `04a` + `04b`)."""
    canonical_valid_cells: dict[str, dict[str, Any]] = {}
    supplementary_valid_trials: dict[str, dict[str, Any]] = {}
    rejected_cells: dict[str, list[str]] = {}
    source_map: dict[str, str] = {}

    for src_label, doc in labeled_docs:
        if doc.get("schema_version") != "cskh-p4-t1b-ab-2x2-vps-diag-v2":
            raise ValueError(
                f"Unexpected schema_version in {src_label}: {doc.get('schema_version')!r}"
            )
        doc_errors = doc.get("errors") or []
        cells = doc.get("cells") or {}
        require_six = any(
            isinstance(c, dict) and isinstance(c.get("waves"), list)
            for c in cells.values()
        )
        for cid, cdoc in cells.items():
            ok, errs = validate_v2_cell(cid, cdoc, require_six_waves=require_six)
            if ok:
                if cid in canonical_valid_cells:
                    prev_src = source_map[cid]
                    supplementary_valid_trials[f"{cid}_prior_{prev_src}"] = (
                        canonical_valid_cells[cid]
                    )
                canonical_valid_cells[cid] = cdoc
                source_map[cid] = src_label
                rejected_cells.pop(cid, None)
            else:
                rej_key = (
                    cid if cid not in canonical_valid_cells else f"{cid}_{src_label}"
                )
                combined_errs = list(errs)
                if doc_errors:
                    combined_errs.append(f"report_errors_count={len(doc_errors)}")
                rejected_cells[rej_key] = combined_errs

        # If a full-2x2 run aborted during B_busy before persisting `cells['B_busy']`, record it explicitly
        if (
            doc.get("mode") == "full-2x2"
            and "B_busy" not in cells
            and "B_busy" not in canonical_valid_cells
            and doc_errors
        ):
            rejected_cells[f"B_busy_{src_label}"] = [
                f"aborted_on_error:{e.get('code') or e}"
                if isinstance(e, dict)
                else str(e)
                for e in doc_errors
            ]

    for cid in ("A_idle", "A_busy", "B_idle", "B_busy"):
        if cid not in canonical_valid_cells and cid not in rejected_cells:
            rejected_cells[cid] = ["missing_cell"]

    slo_matrix: dict[str, dict[str, Any]] = {}
    for slo_id, meta in SIX_SLIPPED_SLO_THRESHOLDS_CAPPED.items():
        mkey = meta["metric_key"]
        thr = float(meta["max_ms"])
        per_cell: dict[str, Any] = {}
        for cid, cdoc in canonical_valid_cells.items():
            val = float((cdoc.get("slo_metrics_summary") or {}).get(mkey, 999999.0))
            per_cell[cid] = {
                "source": source_map.get(cid),
                "measured_ms": val,
                "threshold_ms": thr,
                "passed": val <= thr,
                "headroom_ms": round(thr - val, 3),
            }
        for sup_id, sdoc in supplementary_valid_trials.items():
            val = float((sdoc.get("slo_metrics_summary") or {}).get(mkey, 999999.0))
            per_cell[sup_id] = {
                "measured_ms": val,
                "threshold_ms": thr,
                "passed": val <= thr,
                "headroom_ms": round(thr - val, 3),
            }
        slo_matrix[slo_id] = per_cell

    cfg_b_spec = get_g18_resource_profile_spec("staging_vps_capped")
    cfg_b25_spec = get_g18_resource_profile_spec("staging_vps_capped_b_plus_2_5vcpu")

    decision = "INCOMPLETE_CELLS_AWAITING_FULL_VALID_2X2"
    contingency_b_plus_dossier: dict[str, Any] | None = None

    if "B_busy" in canonical_valid_cells and "B_idle" in canonical_valid_cells:
        failed_on_b_idle = [
            slo_id
            for slo_id in SIX_SLIPPED_SLO_THRESHOLDS_CAPPED
            if not slo_matrix[slo_id]["B_idle"]["passed"]
        ]
        failed_on_b_busy = [
            slo_id
            for slo_id in SIX_SLIPPED_SLO_THRESHOLDS_CAPPED
            if not slo_matrix[slo_id]["B_busy"]["passed"]
        ]
        if not failed_on_b_idle and not failed_on_b_busy:
            decision = "LOCK_CONFIG_B_2_0VCPU_4X4_STAGING_VPS_CAPPED"
        else:
            decision = (
                "ESCALATE_TO_CONFIG_B_PLUS_2_5VCPU_4X4_WITH_MEASURED_JUSTIFICATION"
            )
            contingency_b_plus_dossier = build_config_b_plus_2_5vcpu_justification(
                measured_b_idle_agg03b_p95_ms=slo_matrix["AGG-03B"]["B_idle"][
                    "measured_ms"
                ],
                measured_b_idle_api02b_p95_ms=slo_matrix["API-02B"]["B_idle"][
                    "measured_ms"
                ],
                measured_b_idle_agg03c_p95_ms=slo_matrix["AGG-03C"]["B_idle"][
                    "measured_ms"
                ],
                measured_b_busy_api01c_p95_ms=slo_matrix["API-01C"]["B_busy"][
                    "measured_ms"
                ],
                measured_b_busy_agg03c_p95_ms=slo_matrix["AGG-03C"]["B_busy"][
                    "measured_ms"
                ],
                host_cpu_cores=host_cpu_cores,
                host_mem_total_mib=host_mem_total_mib,
                host_mem_available_mib=host_mem_available_mib,
                host_mem_available_min_during_b_mib=host_mem_available_min_during_b_mib,
                cfg_b25_spec=cfg_b25_spec,
            )

    bg_reconciliation = {
        "official_0127b18_07c93a9f": _extract_bg_slo_verdicts(
            official_g18_eval_0127b18
        ),
        "baseline_35f512c_d3e35f81": _extract_bg_slo_verdicts(
            official_g18_eval_35f512c
        ),
    }

    return {
        "schema_version": "cskh-p4-t1b-ab-2x2-reconciliation-v1",
        "reconciled_at_utc": datetime.now(timezone.utc).isoformat(),
        "intake_status": "RECONCILED",
        "valid_cells": sorted(canonical_valid_cells.keys()),
        "valid_cell_sources": source_map,
        "supplementary_valid_trials": sorted(supplementary_valid_trials.keys()),
        "rejected_cells": rejected_cells,
        "six_slo_reconciliation_by_valid_cell": slo_matrix,
        "background_tasks_reconciliation": bg_reconciliation,
        "decision": decision,
        "locked_primary_profile": {
            "profile_id": cfg_b_spec["profile_id"],
            "slo_spec_profile_column": cfg_b_spec["slo_spec_profile_column"],
            "config_spec_sha256": cfg_b_spec["config_spec_sha256"],
            "compose_env_overrides_sha256": cfg_b_spec["compose_env_overrides_sha256"],
            "verify_9_service_config_spec_sha256": cfg_b_spec[
                "verify_9_service_config_spec_sha256"
            ],
        },
        "config_b_plus_2_5vcpu_contingency_dossier": contingency_b_plus_dossier,
    }


